#include<stdio.h>
//increment operater
//++i pre increment - first increase then use
//i++ post increment - first use then increase
// decrement operater
//--i pre decrement - first decrease then use
//i-- post decrement - first use then decrease
int main(){
    int i=1;
    printf("%d\n",++i);
    printf("%d\n",i);
    printf("%d\n",i++);
    printf("%d\n",i);
    printf("%d\n",--i);
    printf("%d\n",i);
    printf("%d\n",i--);
    printf("%d\n",i);
}